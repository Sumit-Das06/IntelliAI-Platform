"""Manifest writers: the frozen, hash-pinned outputs of this package.

Two shapes, one discipline:

- **Evaluation manifest** — an ``intelliai_evaluation`` ``EvalDataset``
  (path-source clips), written into the evaluation plane's canonical
  datasets directory. One schema, never a second.
- **Training manifest** — the platform's 5-field JSONL
  (``id, audio, text, language, duration_seconds``), byte-deterministic:
  fixed key order, compact separators, LF, trailing newline, samples in
  ascending id order — the same law `apps/api` applies to preparation
  artifacts, so a future trainer consumes either interchangeably.

Every manifest gets a provenance sidecar and a SHA-256 pin. Audio is
never written by this module — only text.
"""

