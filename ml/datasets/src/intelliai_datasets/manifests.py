class ManifestPin(BaseModel):
    """The identity of one written manifest file."""

    model_config = ConfigDict(frozen=True)

    path: str
    sha256: str
    samples: int
    duration_seconds: float


class Provenance(BaseModel):
    """Sidecar: everything a reader needs to trust (or reject) a manifest."""

    model_config = ConfigDict(frozen=True)

    manifest: ManifestPin
    created: str  # ISO date; recorded here, never inside the hashed manifest
    language: str
    sources: tuple[SourceRecord, ...]
    source_splits: tuple[str, ...]  # which official split(s) fed this manifest
    normalization: str  # scoring-time profile this data will be measured under
    primary_ruler: str
    contamination_risk: str
    speaker_ids_available: bool
    speaker_disjointness: str  # honest statement, not a boolean
    curation: str  # the deterministic recipe, in words
    validation: ValidationReport
    notes: str = ""
    # Additive (15C): the dataset repo revision(s) the bytes were retrieved
    # at, the frozen speaker roster (the disjointness enforcement input for
    # every future training freeze), and descriptive statistics.
    source_revisions: dict[str, str] = {}
    speaker_roster: tuple[str, ...] = ()
    statistics: dict[str, dict[str, int]] = {}


def sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1 << 16), b""):
            digest.update(chunk)
    return digest.hexdigest()


def write_train_jsonl(samples: Sequence[CandidateSample], target: Path) -> ManifestPin:
    """Write the 5-field platform JSONL, byte-deterministically."""
    ordered = sorted(samples, key=lambda s: s.id)
    lines = [
        json.dumps(
            {
                "id": sample.id,
                "audio": sample.path,
                "text": normalize_text(sample.text),
                "language": sample.language,
                "duration_seconds": round(sample.duration_seconds, 3),
            },
            ensure_ascii=False,
            separators=(",", ":"),
        )
        for sample in ordered
    ]
    payload = ("\n".join(lines) + "\n").encode("utf-8")
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_bytes(payload)
    return ManifestPin(
        path=target.as_posix(),
        sha256=hashlib.sha256(payload).hexdigest(),
        samples=len(ordered),
        duration_seconds=round(sum(s.duration_seconds for s in ordered), 3),
    )


def build_eval_dataset(
    samples: Sequence[CandidateSample],
    *,
    name: str,
    version: int,
    description: str,
    probes: Sequence[EvalClip] = (),
) -> EvalDataset:
    """Assemble an EvalDataset: natural-speech path clips + probes.

    Clips are ordered by id — stable regardless of ingestion order.
    """
    speech = [
        EvalClip(
            id=sample.id,
            language=sample.language,
            reference_text=normalize_text(sample.text),
            duration_seconds=round(sample.duration_seconds, 3),
            license=sample.license,
            path=sample.path,
            sha256=sample.sha256,
            notes=sample.notes,
        )
        for sample in sorted(samples, key=lambda s: s.id)
    ]
    return EvalDataset(
        name=name,
        version=version,
        capability="transcription",
        description=description,
        clips=[*speech, *probes],
    )


def write_eval_dataset(dataset: EvalDataset, target: Path) -> ManifestPin:
    target.parent.mkdir(parents=True, exist_ok=True)
    payload = (dataset.model_dump_json(indent=2, exclude_none=True) + "\n").encode("utf-8")
    target.write_bytes(payload)
    natural = [c for c in dataset.clips if c.synthetic is None]
    return ManifestPin(
        path=target.as_posix(),
        sha256=hashlib.sha256(payload).hexdigest(),
        samples=len(dataset.clips),
        duration_seconds=round(sum(c.duration_seconds for c in natural), 3),
    )


def write_provenance(provenance: Provenance, target: Path) -> None:
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(
        provenance.model_dump_json(indent=2) + "\n",
        encoding="utf-8",
    )
